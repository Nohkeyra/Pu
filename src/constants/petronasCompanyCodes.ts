// Match legal names exactly after normalization; never use substring/fuzzy matching.
function normalizeName(value: string): string {
  return value.normalize('NFKC').toUpperCase().replace(/[.]/g, '')
    .replace(/\bSENDIRIAN BERHAD\b/g, 'SDN BHD')
    .replace(/\s+/g, ' ').trim();
}
export function resolvePetronasCompany(company: string, registrationNumber?: string): PetronasCompany | undefined {
  // Existing app stores saved company names followed by comma-separated address.
  const name = normalizeName(company.split(/[,\n]/, 1)[0]);
  const names = PETRONAS_COMPANIES.filter(e => normalizeName(e.name) === name);
  if (registrationNumber?.trim()) {
    const reg = registrationNumber.trim().toUpperCase();
    const matches = PETRONAS_COMPANIES.filter(e => e.registrationNumber?.toUpperCase() === reg);
    if (matches.length !== 1 || (name && !names.some(e => e.code === matches[0].code))) return undefined;
    return matches[0];
  }
  return names.length === 1 ? names[0] : undefined;
}
export function getCompanyCode(company: string, registrationNumber?: string): string {
  return resolvePetronasCompany(company, registrationNumber)?.code ?? '';
}
// Only for confirmed email-collector eligible individual invoices.
export function buildPetronasInvoiceSubject(companyCode: string, invoiceNo: string): string | undefined {
  if (!PETRONAS_COMPANIES.some(e => e.code === companyCode) || !/^RW\d{5}$/.test(invoiceNo)) return undefined;
  return `${companyCode} ${invoiceNo}`;
}
